/** Traduction d'une clé dans la langue donnée (repli : français). */
export function t(lang: string, key: TranslationKey): string {
  const dict = DICT[lang as LanguageCode];
  return dict?.[key] ?? FR[key];
}

/** Objet traducteur pratique : const tr = translator(lang); tr("nav.home") */
export function translator(lang: string): (key: TranslationKey) => string {
  return (key) => t(lang, key);
}
