import { z } from "zod";

const optionalText = (max: number) => z.string().trim().max(max).optional();
const optionalList = (maxItems: number, maxLength = 100) =>
  z.array(z.string().trim().min(1).max(maxLength)).max(maxItems).optional();

export const sellerOnboardingResponsesSchema = z.object({
  sellerType: z.enum(["individual", "entrepreneur", "company", "association", "organization"]).optional(),
  commercialName: optionalText(120),
  phone: optionalText(30),
  country: optionalText(80),
  city: optionalText(100),
  businessAddress: optionalText(200),
  foundedYear: z.number().int().min(1800).max(new Date().getFullYear()).optional(),
  categories: optionalList(10, 80),
  specialty: optionalText(160),
  yearsActive: optionalText(80),
  offering: optionalText(1200),
  mission: optionalText(800),
  differentiator: optionalText(800),
  commercialGoals: optionalText(600),
  targetCustomer: optionalText(500),
  digitalProducts: optionalList(12, 100),
  physicalProducts: optionalList(10, 100),
  services: optionalList(10, 100),
  mainProduct: optionalText(180),
  plannedProducts: z.number().int().min(0).max(100000).optional(),
  averagePriceXOF: z.number().int().min(0).max(100000000).optional(),
  offerAudience: optionalText(400),
  offerValue: optionalText(800),
  otherPlatforms: optionalText(400),
  competitors: optionalText(400),
  publicName: optionalText(80),
  slogan: optionalText(160),
  shortDescription: optionalText(400),
  fullPresentation: optionalText(2000),
  logoUrl: z.string().url().max(500).optional().or(z.literal("")),
  coverUrl: z.string().url().max(500).optional().or(z.literal("")),
  primaryColor: z.string().regex(/^#[0-9a-fA-F]{6}$/).optional(),
  secondaryColor: z.string().regex(/^#[0-9a-fA-F]{6}$/).optional(),
  visualStyle: optionalText(100),
  publicContact: optionalText(160),
  website: z.string().url().max(300).optional().or(z.literal("")),
  socialLinks: optionalText(500),
  targetAudience: optionalText(500),
  customerAge: optionalText(100),
  targetCountries: optionalText(300),
  customerProblems: optionalText(800),
  socialNetworks: optionalList(12, 80),
  customerAcquisition: optionalText(500),
  monthlySalesGoalXOF: z.number().int().min(0).max(1000000000).optional(),
  wantsAffiliates: z.boolean().optional(),
  digitalFormats: optionalList(12, 80),
  approximateFileSize: optionalText(100),
  digitalDelivery: optionalText(500),
  postPurchaseInstructions: optionalText(800),
  shippingZones: optionalText(400),
  shippingFees: optionalText(300),
  shippingDelay: optionalText(200),
  stockManagement: optionalText(300),
  orderProcessing: optionalText(400),
  serviceDelivery: optionalText(500),
  serviceDelay: optionalText(200),
  needsAppointment: z.boolean().optional(),
  serviceInstructions: optionalText(600),
  refundPolicy: optionalText(800),
  salesConditions: optionalText(1000),
  productUsageTerms: optionalText(800),
  customerInstructions: optionalText(800),
  supportEmail: z.string().email().max(160).optional().or(z.literal("")),
  mainGoal: optionalText(400),
  internationalSales: z.boolean().optional(),
  recruitAffiliates: z.boolean().optional(),
  interestedFeatures: optionalList(12, 100),
  onlineSalesChallenges: optionalText(800),
}).strict();

export type SellerOnboardingResponses = z.infer<typeof sellerOnboardingResponsesSchema>;
